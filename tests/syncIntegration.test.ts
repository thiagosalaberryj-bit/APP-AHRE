import test from 'node:test';
import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {join} from 'node:path';
import type {Server} from 'node:http';
import {randomUUID} from 'node:crypto';
import {preparar} from './helpers/localDatabase.ts';
const rutaServidor=process.env.AHRE_SERVER_SOURCE;
type Fila=Record<string,string|number|null>;
interface BaseRemota {get:(sql:string,parametros?:(string|number|null)[])=>Promise<Fila|undefined>;close:()=>Promise<void>;}
test('integración real MySQL: offline, reemplazo confirmado, revocación, pendientes y desvinculación normal',{skip:!rutaServidor||process.env.AHRE_MYSQL_TEST!=='1'},async t=>{
  const cargarServidor=createRequire(join(rutaServidor!,'backend/package.json'));
  const mysql=cargarServidor('mysql2/promise') as {createConnection:(opciones:object)=>Promise<{query:(sql:string)=>Promise<unknown>;end:()=>Promise<void>}>};
  const {prepararAplicacion}=cargarServidor('./dist/app.js') as {prepararAplicacion:(opciones:object)=>Promise<{app:{listen:(puerto:number,host:string)=>Server};db:BaseRemota}>};
  const configuracion={host:process.env.DB_HOST||'127.0.0.1',port:Number(process.env.DB_PORT)||3306,user:process.env.DB_USER||'root',password:process.env.DB_PASSWORD||''};
  const admin=await mysql.createConnection(configuracion),nombre='ahre_test_'+randomUUID().replaceAll('-','');
  await admin.query('CREATE DATABASE '+nombre);
  t.after(async()=>{assert.match(nombre,/^ahre_test_[a-f0-9]{32}$/);await admin.query('DROP DATABASE '+nombre);await admin.end();});
  const {app,db}=await prepararAplicacion({...configuracion,database:nombre}),servidor=app.listen(0,'127.0.0.1');
  await new Promise<void>(r=>servidor.once('listening',r));t.after(async()=>{servidor.closeAllConnections();await new Promise<void>(r=>servidor.close(()=>r()));await db.close();});
  const direccion=servidor.address();assert.ok(direccion&&typeof direccion!=='string');
  const puerto=direccion.port,url=`http://127.0.0.1:${puerto}/api/v1`;let offline=false;
  const transporte:typeof fetch=async(...args)=>{if(offline)throw new Error('sin red');return fetch(...args);};
  const uno=await preparar(t,true,{url,fetch:transporte});
  await uno.prepararDatosPrueba({sincronizar:true});
  let vista={estado:''};const dejar=uno.observarSincronizacion(v=>{vista=v;});
  t.after(dejar);
  assert.equal(vista.estado,'online',JSON.stringify(vista));
  assert.equal((await db.get('SELECT COUNT(*) n FROM gastos_compartidos'))!.n,4);
  assert.equal(uno.base.prepare('SELECT COUNT(*) n FROM sync_outbox').get()!.n,0);
  const usuario=(await uno.obtenerSesionActual()).usuario!;
  offline=true;
  await uno.iniciarSesion({correo:'pruebas@ahre.test',contrasena:'AhrePruebas2026!',recordar:false});
  assert.equal((await uno.obtenerSesionActual()).usuario!.id,usuario.id);
  assert.equal(vista.estado,'offline');
  const deposito=await uno.depositosRepositorio.crear({usuario_id:usuario.id,nombre:'Offline real',tipo:'efectivo',saldo_inicial:1000,icono:'cash-outline',fecha_creacion:'2020-01-01T00:00:00.000Z'});
  await uno.movimientosRepositorio.crear({deposito_id:deposito.id,categoria:'alimentacion',tipo:'egreso',monto:125,descripcion:'Compra real offline',fecha_hora:new Date().toISOString()});
  await uno.sincronizarCuenta(usuario.id);assert.equal(vista.estado,'offline');
  assert.equal(await db.get('SELECT id FROM depositos WHERE id=?',[deposito.id]),undefined);
  offline=false;await uno.sincronizarCuenta(usuario.id);assert.equal(vista.estado,'online');
  assert.equal((await db.get('SELECT saldo_actual FROM depositos WHERE id=?',[deposito.id]))!.saldo_actual,875);
  const dos=await preparar(t,true,{url,fetch:transporte});
  offline=true;
  await assert.rejects(dos.iniciarSesion({correo:'pruebas@ahre.test',contrasena:'AhrePruebas2026!',recordar:false}),/Conectate/);
  assert.equal(dos.base.prepare('SELECT COUNT(*) n FROM usuarios').get()!.n,0);
  offline=false;
  await assert.rejects(dos.iniciarSesion({correo:'pruebas@ahre.test',contrasena:'AhrePruebas2026!',recordar:false}),/otra instalación/);
  assert.equal(dos.base.prepare('SELECT COUNT(*) n FROM usuarios').get()!.n,0);
  await dos.iniciarSesion({correo:'pruebas@ahre.test',contrasena:'AhrePruebas2026!',recordar:false,reemplazarDispositivo:true});
  assert.equal((await dos.cargarSocial()).salas[0].gastos.length,4);
  assert.equal(dos.base.prepare('SELECT saldo_actual FROM depositos WHERE id=?').get(deposito.id)!.saldo_actual,875);
  await dos.cerrarSala((await dos.cargarSocial()).salas[0].id);await dos.sincronizarCuenta(usuario.id);
  await uno.sincronizarCuenta(usuario.id);
  assert.equal(vista.estado,'revocado');
  assert.equal((await uno.obtenerSesionActual()).usuario,null);
  await uno.iniciarSesion({correo:'pruebas@ahre.test',contrasena:'AhrePruebas2026!',recordar:false,reemplazarDispositivo:true});
  assert.equal((await uno.cargarSocial()).salas[0].estado,'cerrada');
  assert.equal((await uno.cargarSocial()).deudas.length,5);
  offline=true;
  const pendiente=await uno.depositosRepositorio.crear({usuario_id:usuario.id,nombre:'No sincronizado',tipo:'efectivo',saldo_inicial:200,icono:'cash-outline'});
  const colaAnterior=JSON.stringify(uno.base.prepare('SELECT * FROM sync_outbox ORDER BY secuencia').all());
  offline=false;
  await dos.iniciarSesion({correo:'pruebas@ahre.test',contrasena:'AhrePruebas2026!',recordar:false,reemplazarDispositivo:true});
  await uno.sincronizarCuenta(usuario.id);
  assert.equal(vista.estado,'revocado');
  assert.equal(JSON.stringify(uno.base.prepare('SELECT * FROM sync_outbox ORDER BY secuencia').all()),colaAnterior);
  assert.equal(await db.get('SELECT id FROM depositos WHERE id=?',[pendiente.id]),undefined);
  await assert.rejects(uno.depositosRepositorio.actualizar(pendiente.id,{nombre:'Bloqueado'}));
  await assert.rejects(uno.iniciarSesion({correo:'pruebas@ahre.test',contrasena:'AhrePruebas2026!',recordar:false,reemplazarDispositivo:true}),/autorización anterior/);
  const autorizada=(await dos.obtenerSesionRemota(usuario.id))!;
  await dos.solicitarRemoto('/auth/status',undefined,autorizada.token);
  await dos.prepararCambioDispositivo();
  assert.equal((await dos.obtenerSesionActual()).usuario,null);
  const tres=await preparar(t,true,{url,fetch:transporte});
  await tres.iniciarSesion({correo:'pruebas@ahre.test',contrasena:'AhrePruebas2026!',recordar:false});
  assert.equal((await tres.cargarSocial()).salas[0].estado,'cerrada');
  assert.deepEqual(uno.base.prepare('PRAGMA foreign_key_check').all(),[]);
  assert.deepEqual(dos.base.prepare('PRAGMA foreign_key_check').all(),[]);
});
